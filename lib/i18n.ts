export function tr(lang: Lang, key: string, vars: Record<string, string | number> = {}) {
  let s = dicts[lang][key] ?? dicts.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
